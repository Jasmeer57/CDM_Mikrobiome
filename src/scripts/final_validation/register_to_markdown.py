"""Write every number the paper may use, from the claims register, into one Markdown reference file.

    python src/scripts/final_validation/register_to_markdown.py [--out FILE]

Reads MANUSCRIPT_CLAIMS_REGISTER.csv and the dated corrections file; adds the known ambiguities and the numbers that
are not registered. Copies values; computes nothing. Reference notes for the authors, not manuscript text.
"""
from __future__ import annotations

import argparse
import collections
import csv
import datetime
import hashlib
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / ".cdm_root").is_file())
FV = ROOT / "paper/publication/final_validation"
REG = FV / "MANUSCRIPT_CLAIMS_REGISTER.csv"
CORR = sorted(FV.glob("MANUSCRIPT_CLAIMS_REGISTER_CORRECTIONS_*.csv"))

LAYERS = [
    ("Papers", "453 corpus [C01] / 447 distinct publications [C02] / 452 NER-variant runs / 444 old 2026-08 build",
     "453 for corpus and terminology, 447 for canonical layers; never 444"),
    ("Mentions", "2,505,684 in CDM 3.0.3 [M01] / 2,505,735 in terminology 1.0.1 [M02]", "M01; name the layer"),
    ("CPU ensemble mentions", "1,705,449 in CDM [M03] / 1,705,501 in terminology 1.0.1", "M03"),
    ("Canonical terms", "162,409 after review [T02] / 165,991 before review [T01]", "T02 (corrections T-02a)"),
    ("Mappings", "334,231 candidates → 314,772 kept → 18,272 accepted [P01, P02, P05] / 331,394 term_concept_map rows",
     "P01/P02/P05; 331,394 is DO_NOT_CITE (M-01)"),
    ("Triples supported by their sentence", "22.0% original label supported [Q04] / 56.0% claim supported [W03]",
     "different rubrics and runs; say which (W05 reconciles)"),
    ("Triple screen counts", "16,032 CC BY/CC0 triples [W02] / 14,363·5,780·4,618 all-licence",
     "W02/W03 only; all-licence counts are DO_NOT_CITE (B-01–B-04)"),
    ("Compendium samples", "168,464 total [C06] / 156,330 in corpus BioProjects [C05] / '168,000' in cited title",
     "C06 + C05/C09; BioProject-level linkage only"),
    ("Two CDM builds", "CDM 3.0.3 (44 tables, 25,788 triples) / frozen_output v2-era (110,981 entities, 32,713 triples)",
     "never mix; the paper uses 3.0.3"),
]

UNREGISTERED = [
    ("482 BioProjects in the compendium", "Introduction draft"),
    ("274 open / 179 restricted papers (rights split)", "BIB_MANUSCRIPT_PLAN.md"),
    ("S1000 species F1 (PubTator3 0.705, Qwen3.5-4B 3-shot 0.632, HunFlair2 0.631)",
     "outputs/results/benchmark/ner_species_s1000/species_metrics.json"),
    ("'7 models' in the CPU section ensemble", "pipeline flowchart"),
    ("6.5% of triple-evidence mentions unanchored; 9,940 unreachable terms; 215 off-vocabulary values",
     "Workstream A report / 02_results.md"),
    ("392,587 text values; 12,114 counts; 42,679 coded values; 52,397 assessable records", "02_results.md"),
    ("34,416 relation_evidence rows", "corrections E-01 (DO_NOT_CITE)"),
    ("Grounding by type (organisms 12.2/48.5, chemicals 18.5/50.0, diseases 16.1/54.5, proteins 11.1/27.6)",
     "Workstream C report"),
    ("All-labels κ 0.084 between the two catalogue judges", "S6 matrix"),
    ("126 numbers marked REPORT in MANUSCRIPT_NUMBER_AUDIT.csv", "MANUSCRIPT_NUMBER_AUDIT.csv"),
]


def esc(s: str) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ").strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=FV / f"PAPER_NUMBERS_{datetime.date.today()}.md")
    a = ap.parse_args()
    rows = list(csv.DictReader(open(REG, encoding="utf-8")))
    reg_sha = hashlib.sha256(REG.read_bytes()).hexdigest()
    ids = collections.Counter(r["claim_id"] for r in rows)
    dups = sorted(k for k, v in ids.items() if v > 1)
    status = collections.Counter(r["status"] for r in rows)
    sections = list(dict.fromkeys(r["section"] for r in rows))

    L = [f"# Paper numbers: every registered value ({datetime.date.today()})", "",
         "*Reference notes for the authors, generated by `src/scripts/final_validation/register_to_markdown.py` from "
         "the claims register. **Not manuscript text**: write the paper yourselves and cite the IDs. Values are copied "
         "from the register, which recomputes each from the frozen data; nothing here is accuracy unless it is F1 on a "
         "public gold standard. No human annotation was done [H01].*", "",
         f"- Register: `{REG.relative_to(ROOT)}`, {len(rows)} rows, sha256 `{reg_sha[:16]}…`",
         f"- Status: " + ", ".join(f"{k} {v}" for k, v in status.most_common()),
         f"- Frozen data verified 2026-11-08: CDM 3.0.3 db sha256 5d23ba87…, 17 release manifests and the 119-file "
         "FINAL_VALIDATION_MANIFEST all match. The register itself is versioned (change log), not under a manifest.",
         "- Values with `/` are several numbers in the order the claim names them.", ""]
    if dups:
        L += ["> **Duplicate IDs: " + ", ".join(dups) + ".** Each is used for two different claims (marked ⚠ below). "
              "Renumber one set before citing any of them.", ""]
    L += ["## Contents", ""] + [f"- [{s}](#{s.lower().replace(' ', '-').replace('.', '')})" for s in sections] + [
        "- [Rows not to cite, and corrections](#rows-not-to-cite-and-corrections)",
        "- [Same quantity, several values](#same-quantity-several-values)",
        "- [Numbers used in drafts but not registered](#numbers-used-in-drafts-but-not-registered)", ""]
    for s in sections:
        L += [f"## {s}", "", "| ID | Claim | Value | Source |", "|---|---|---|---|"]
        for r in rows:
            if r["section"] == s:
                flag = " ⚠" if r["claim_id"] in dups else ""
                val = esc(r["stated"]) + ("" if r["status"] == "MATCH" else f" ({r['status']})")
                L.append(f"| {r['claim_id']}{flag} | {esc(r['claim'])} | {val} | {esc(r['source'])} |")
        L.append("")

    L += ["## Rows not to cite, and corrections", ""]
    for c in CORR:
        L += [f"From `{c.relative_to(ROOT)}`:", "", "| ID | Claim | Value | Status | Note |", "|---|---|---|---|---|"]
        for r in csv.DictReader(open(c, encoding="utf-8")):
            if not r["claim_id"].strip():
                continue
            L.append(f"| {r['claim_id']} | {esc(r['claim'])[:140]} | {esc(r['stated'])} | {esc(r['status'])} | "
                     f"{esc(r['source'])[:200]} |")
        L.append("")
    L += ["## Same quantity, several values", "", "| Quantity | Values | Cite |", "|---|---|---|"]
    L += [f"| {q} | {v} | {c} |" for q, v, c in LAYERS] + [""]
    L += ["## Numbers used in drafts but not registered", "",
          "These may be correct but have not been recomputed into the register. Add a row before citing.", "",
          "| Number | Where it appears |", "|---|---|"] + [f"| {n} | {w} |" for n, w in UNREGISTERED] + [""]
    L += ["## Do not claim", "",
          "Accuracy, recall, completeness or \"validated\" for the CDM; \"LLMs beat NLP\"; human validation; public "
          "availability or a DOI before release; Claim F 100%; judge pass rates as accuracy; anything about the "
          "168K compendium beyond BioProject-level linkage (MASTER_VALIDATION_REPORT.md, \"Not allowed\").", ""]
    a.out.write_text("\n".join(L), encoding="utf-8")
    print(a.out.relative_to(ROOT), len(rows), "rows;", "dups:", dups)


if __name__ == "__main__":
    main()
