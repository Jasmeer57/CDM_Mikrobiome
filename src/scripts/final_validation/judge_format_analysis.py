"""Separate output-format failures from real disagreement between the two catalogue judges (Llama-3.1-8B, Mistral-7B).

    python3 src/scripts/final_validation/judge_format_analysis.py

Reads the frozen judge outputs (paper/publication/final_validation/evidence_judge/{llama,mistral}.shard*.jsonl) and
writes outputs/results/benchmark/judge_format_analysis_2026-11-09/{summary.json,REPORT.md}. A verdict is valid when it
is PASS, UNCERTAIN or FAIL_*; anything else (field values, YES/NO, free text) is a format failure.
Reports observed agreement, Cohen's kappa and PABAK (prevalence- and bias-adjusted kappa, 2*po-1) per layer.
"""
import collections, glob, json, re
from pathlib import Path
ROOT = next(p for p in Path(__file__).resolve().parents if (p / ".cdm_root").is_file())
import argparse
_ap = argparse.ArgumentParser()
_ap.add_argument("--src", type=Path, default=ROOT / "paper/publication/final_validation/evidence_judge")
_ap.add_argument("--out", type=Path, default=ROOT / "outputs/results/benchmark/judge_format_analysis_2026-11-09")
_a = _ap.parse_args()
SRC, OUT = _a.src, _a.out
def load(j):
    d = {}
    for f in sorted(SRC.glob(f"{j}.shard*.jsonl")):
        for l in open(f, encoding="utf-8"):
            try: r = json.loads(l)
            except ValueError: continue
            for k, v in (r.get("fields") or {}).items(): d[(r["table"], r["record_id"], k)] = v
    return d
def cls(v): return "PASS" if v == "PASS" else "UNC" if v == "UNCERTAIN" else "FAIL" if str(v).startswith("FAIL") else "INVALID"
def agree(p):
    n = len(p); po = sum(a == b for a, b in p) / n
    ca, cb = collections.Counter(a for a, _ in p), collections.Counter(b for _, b in p)
    pe = sum(ca[x] * cb[x] for x in set(ca) | set(cb)) / n / n
    return {"n": n, "observed": round(po, 3), "kappa": round((po - pe) / (1 - pe), 3), "pabak": round(2 * po - 1, 3)}
L, M = load("llama"), load("mistral"); keys = sorted(set(L) & set(M))
out = {"what": "catalogue judges, field-level verdicts; model judgements, not accuracy", "field_verdicts": len(keys)}
for name, D in (("llama", L), ("mistral", M)):
    inv = [str(D[k]) for k in keys if cls(D[k]) == "INVALID"]
    out[name] = {"invalid": len(inv), "invalid_pct": round(100 * len(inv) / len(keys), 1),
                 "top_invalid_tokens": collections.Counter(x[:30] for x in inv).most_common(10)}
pairs = [(cls(L[k]), cls(M[k])) for k in keys]
bv = [(a, b) for a, b in pairs if "INVALID" not in (a, b)]
pf = [(a, b) for a, b in bv if "UNC" not in (a, b)]
out["all_pairs"] = agree(pairs); out["both_valid"] = agree(bv); out["pass_vs_fail_both_decided"] = agree(pf)
out["pass_share_when_decided"] = round(sum(1 for a, _ in pf if a == "PASS") / len(pf), 3)
out["both_valid_share_of_pairs"] = round(len(bv) / len(pairs), 3)
out["both_valid_crosstab_llama_rows_mistral_cols"] = {a: {b: sum(1 for x, y in bv if x == a and y == b) for b in ("PASS", "FAIL", "UNC")} for a in ("PASS", "FAIL", "UNC")}
dis = [(a, b) for a, b in bv if a != b]
out["disagreements_both_valid"] = {"total": len(dis), "pass_vs_fail": sum(1 for a, b in dis if {a, b} == {"PASS", "FAIL"}),
                                   "involving_uncertain": sum(1 for a, b in dis if "UNC" in (a, b))}
OUT.mkdir(parents=True, exist_ok=True)
json.dump(out, open(OUT / "summary.json", "w"), indent=1)
R = [f"# Catalogue judges: format failures vs disagreement ({SRC.name})", "",
     "Generated by `src/scripts/final_validation/judge_format_analysis.py` from the frozen judge outputs. Model judgements, not accuracy.", "",
     f"- Field verdicts per judge: {len(keys):,}",
     f"- Invalid-format verdicts: Llama {out['llama']['invalid_pct']}%, Mistral {out['mistral']['invalid_pct']}% (top Mistral tokens: " + ", ".join(f"{t} {c:,}" for t, c in out['mistral']['top_invalid_tokens'][:6]) + ")",
     f"- All pairs: observed {out['all_pairs']['observed']}, kappa {out['all_pairs']['kappa']}",
     f"- Both valid ({100*out['both_valid_share_of_pairs']:.1f}% of pairs): observed {out['both_valid']['observed']}, kappa {out['both_valid']['kappa']}",
     f"- PASS vs FAIL, both decided: observed {out['pass_vs_fail_both_decided']['observed']}, kappa {out['pass_vs_fail_both_decided']['kappa']}, PABAK {out['pass_vs_fail_both_decided']['pabak']}; PASS share {out['pass_share_when_decided']} (kappa paradox)",
     f"- Disagreements among valid pairs: {out['disagreements_both_valid']['total']:,} = PASS-vs-FAIL {out['disagreements_both_valid']['pass_vs_fail']:,} + one UNCERTAIN {out['disagreements_both_valid']['involving_uncertain']:,}", "",
     ("Reading: " + ("Mistral's output-format failures remove most pairs from comparison; " if out["mistral"]["invalid_pct"] > 5 else "format failures are negligible in this run; ")
      + f"kappa is further lowered by the {100*out['pass_share_when_decided']:.0f}% PASS prevalence (see PABAK) and by different use of UNCERTAIN; "
      + f"opposite PASS/FAIL verdicts are {100*out['disagreements_both_valid']['pass_vs_fail']/out['both_valid']['n']:.1f}% of valid pairs."), ""]
(OUT / "REPORT.md").write_text("\n".join(R), encoding="utf-8"); print("\n".join(R))
