"""Explain the 2 FAIL and 1 CONDITIONAL results of the 121 CDM constraint tests [X07] (deterministic, read-only).

    python src/scripts/final_validation/x07_test_exceptions.py

The tests come from releases/cdm_v3/3.0.3/remediation/regression/cdm_validation_proposed_registry/
CDM_CONSTRAINT_TEST_RESULTS.csv. CDM 3.0.3 and 3.1.0 hold the same 44 core tables, so the results apply to both.
The frozen databases are NOT changed; this script measures what each non-pass consists of so it can be documented.
Output: paper/publication/final_validation/X07_TEST_EXCEPTIONS_2026-11-10.{json,md}. Written with Claude Code (declare).
"""
from __future__ import annotations

import csv
import json
import sqlite3
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / ".cdm_root").is_file())
DB = ROOT / "releases/cdm_v3/3.1.0/microbiome_cdm_v3.1.0.db"
RES = ROOT / "releases/cdm_v3/3.0.3/remediation/regression/cdm_validation_proposed_registry/CDM_CONSTRAINT_TEST_RESULTS.csv"
OUT = ROOT / "paper/publication/final_validation/X07_TEST_EXCEPTIONS_2026-11-10"
S9 = [("cohort", "participant_count"), ("cohort", "sample_count"), ("sample", "sample_count"), ("data_asset", "file_size_bytes")]
MISSING = ("", "NOT_REPORTED", "CONFLICTING", "NOT_APPLICABLE", "UNCLEAR")


def main():
    c = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    q = lambda s, *a: c.execute(s, a).fetchone()[0]  # noqa: E731
    tests = {r["test_id"]: r for r in csv.DictReader(open(RES, encoding="utf-8"))}
    nonpass = {k: v["result"] for k, v in tests.items() if v["result"] != "PASS"}
    s4 = {"dataset_rows": q("SELECT COUNT(*) FROM dataset"),
          "failing_ids": q("SELECT COUNT(*) FROM dataset WHERE dataset_id NOT GLOB 'HMDATA_[0-9][0-9][0-9][0-9][0-9][0-9]'"),
          "failing_ids_of_form_HMDATA_BP_nnnnnn": q("SELECT COUNT(*) FROM dataset WHERE dataset_id GLOB 'HMDATA_BP_[0-9][0-9][0-9][0-9][0-9][0-9]'"),
          "failing_ids_that_are_BioProject_links": q("SELECT COUNT(*) FROM dataset WHERE dataset_id GLOB 'HMDATA_BP_*' AND accession_type='BioProject'"),
          "ids_unique": q("SELECT COUNT(*) = COUNT(DISTINCT dataset_id) FROM dataset") == 1}
    s9 = {}
    for t, col in S9:
        texts = dict(c.execute(f"SELECT {col}, COUNT(*) FROM {t} WHERE typeof({col})='text' GROUP BY 1").fetchall())
        s9[f"{t}.{col}"] = {"text_values": sum(texts.values()), "by_value": texts,
                            "text_values_that_are_numbers": sum(n for v, n in texts.items() if v.strip().lstrip("-").replace(".", "", 1).isdigit()),
                            "text_values_not_missing_codes": sum(n for v, n in texts.items() if v not in MISSING)}
    n3 = dict(c.execute("SELECT COALESCE(source_pipeline, extraction_run_id), COUNT(*) FROM claim GROUP BY 1").fetchall()) \
        if "source_pipeline" in [r[1] for r in c.execute("PRAGMA table_info(claim)")] else tests["N3"]["detail"]
    out = {"tests": len(tests), "non_pass": nonpass,
           "S4": {**s4, "explanation": "the only non-matching ids are HMDATA_BP_nnnnnn: dataset rows that link a paper to its "
                  "corpus BioProject (not extracted from the text); a distinct prefix on purpose. Ids are unique. "
                  "The registry pattern ^HMDATA_[0-9]{6}$ does not list this second form."},
           "S9": {"columns": s9, "explanation": "every text value in these integer columns is an empty string or a missing-data "
                  "code (NOT_REPORTED, CONFLICTING); no malformed number is stored. Mixed storage is the coding convention "
                  "for missing values, not corrupt data; a typed column plus a separate status column is a schema change "
                  "for a later release."},
           "N3": {"detail": tests["N3"]["detail"], "claim_rows_by_source": n3,
                  "explanation": "CLAIM holds two independent extractions (catalogue v3.1 and corpus stage 52); their overlap "
                  "is not reconciled. Reconciliation is an expert design decision (blocker B12), left open and disclosed."},
           "frozen_data_changed": False}
    OUT.with_suffix(".json").write_text(json.dumps(out, indent=1, default=str) + "\n", encoding="utf-8")
    md = ["# X07: the 3 non-passing CDM constraint tests (of 121)", "",
          f"Generated by `src/scripts/final_validation/x07_test_exceptions.py` from CDM 3.1.0 (core tables identical to 3.0.3). "
          "Frozen data unchanged. Facts for the authors; not manuscript text.", "",
          "| Test | Result | What it consists of |", "|---|---|---|",
          f"| S4 dataset_id pattern | FAIL | {s4['failing_ids']} of {s4['dataset_rows']:,} ids; all {s4['failing_ids_of_form_HMDATA_BP_nnnnnn']} are "
          f"`HMDATA_BP_nnnnnn` BioProject-link rows ({s4['failing_ids_that_are_BioProject_links']} with accession_type BioProject); ids unique: {s4['ids_unique']} |",
          "| S9 one storage type per column | FAIL | " + "; ".join(
              f"{k}: {v['text_values']:,} text values, {v['text_values_not_missing_codes']} not empty/missing code, {v['text_values_that_are_numbers']} numeric"
              for k, v in s9.items()) + " |",
          f"| N3 one representation per finding | CONDITIONAL | {tests['N3']['detail']} |", "",
          "**Reading:** none of the three is corrupt data. S4 is a second, intentional id form; S9 is the missing-value "
          "coding convention; N3 is an open design decision (B12). A schema fix (typed counts + status column; registry "
          "pattern for BioProject links; claim reconciliation) belongs to a later release, not to the frozen ones."]
    OUT.with_suffix(".md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(json.dumps(out, indent=1, default=str)[:3000])


if __name__ == "__main__":
    main()
