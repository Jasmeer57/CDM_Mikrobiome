def normalize_predicate(raw: str) -> str:
    """Normalize a raw predicate string to canonical CDM predicate.

    Returns the canonical predicate, or the lowercased raw if no mapping found.
    """
    if not raw:
        return "associated_with"
    key = raw.strip().lower()
    if key in CANONICAL_PREDICATES:
        return key
    if key in PREDICATE_SYNONYM_MAP:
        return PREDICATE_SYNONYM_MAP[key]
    # Try without leading "is "
    if key.startswith("is ") and key[3:] in PREDICATE_SYNONYM_MAP:
        return PREDICATE_SYNONYM_MAP[key[3:]]
    # Try without trailing "s"
    if not key.endswith("s") and key + "s" in PREDICATE_SYNONYM_MAP:
        return PREDICATE_SYNONYM_MAP[key + "s"]
    return key


def is_correlational_evidence(evidence: str) -> bool:
    """Check if evidence text is purely correlational (not causal).

    Used for direction-demotion: if predicate is directional but evidence
    only shows correlation, demote to associated_with.
    """
    if not evidence:
        return False
    ev_lower = evidence.lower()
    has_hedge = any(h in ev_lower for h in HEDGE_WORDS)
    has_strong = any(s in ev_lower for s in STRONG_EVIDENCE_WORDS)
    return has_hedge and not has_strong

